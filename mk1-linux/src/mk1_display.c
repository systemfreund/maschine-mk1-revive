void mk1_canvas_clear(mk1_canvas_t *c, uint8_t gray)
{
    memset(c->px, gray, sizeof(c->px));
}

void mk1_canvas_fill_rect(mk1_canvas_t *c, int x, int y, int w, int h, uint8_t gray)
{
    int x0 = x < 0 ? 0 : x, y0 = y < 0 ? 0 : y;
    int x1 = x + w > MK1_DISPLAY_WIDTH ? MK1_DISPLAY_WIDTH : x + w;
    int y1 = y + h > MK1_DISPLAY_HEIGHT ? MK1_DISPLAY_HEIGHT : y + h;
    for (int yy = y0; yy < y1; yy++) {
        for (int xx = x0; xx < x1; xx++) {
            c->px[yy][xx] = gray;
        }
    }
}

void mk1_canvas_frame_rect(mk1_canvas_t *c, int x, int y, int w, int h, uint8_t gray)
{
    mk1_canvas_fill_rect(c, x, y, w, 1, gray);
    mk1_canvas_fill_rect(c, x, y + h - 1, w, 1, gray);
    mk1_canvas_fill_rect(c, x, y, 1, h, gray);
    mk1_canvas_fill_rect(c, x + w - 1, y, 1, h, gray);
}

int mk1_text_width(const char *text, int scale)
{
    size_t n = strlen(text);
    return n ? (int)n * (MK1_FONT_W + 1) * scale - scale : 0;
}

int mk1_canvas_text(mk1_canvas_t *c, int x, int y, const char *text, int scale, uint8_t gray)
{
    for (const unsigned char *p = (const unsigned char *)text; *p; p++) {
        unsigned ch = (*p >= 0x20 && *p <= 0x7e) ? *p : '?';
        const uint8_t *glyph = k_font[ch - 0x20];
        for (int col = 0; col < MK1_FONT_W; col++) {
            for (int row = 0; row < MK1_FONT_H; row++) {
                if (glyph[col] & (1u << row)) {
                    mk1_canvas_fill_rect(c, x + col * scale, y + row * scale, scale, scale, gray);
                }
            }
        }
        x += (MK1_FONT_W + 1) * scale;
    }
    return x;
}

void mk1_canvas_pack(const mk1_canvas_t *c, uint8_t fb[MK1_DISPLAY_FB_BYTES])
{
    for (int y = 0; y < MK1_DISPLAY_HEIGHT; y++) {
        uint8_t *row = fb + y * MK1_DISPLAY_ROW_BYTES;
        for (int g = 0; g < MK1_DISPLAY_ROW_BYTES / 2; g++) {
            uint8_t a = c->px[y][g * 3]     & MK1_DISPLAY_MAX_GRAY;
            uint8_t b = c->px[y][g * 3 + 1] & MK1_DISPLAY_MAX_GRAY;
            uint8_t d = c->px[y][g * 3 + 2] & MK1_DISPLAY_MAX_GRAY;
            row[g * 2]     = (uint8_t)((a << 3) | (b >> 2));
            row[g * 2 + 1] = (uint8_t)((b << 6) | d);
        }
    }
}

// 18-command init sequence from the macOS bridge (mk1_device_init_hardware).
const mk1_display_cmd_t mk1_display_init_cmds[] = {
    { 1, { 0x30 } },                    // enter extension set
    { 4, { 0xca, 0x04, 0x0f, 0x00 } },  // duty / display lines
    { 2, { 0xbb, 0x00 } },              // COM scan direction
    { 1, { 0xd1 } },                    // oscillator on
    { 1, { 0x94 } },                    // sleep out
    { 3, { 0x81, 0x1e, 0x02 } },        // electronic volume
    { 2, { 0x20, 0x08 } },              // power control
    { 2, { 0x20, 0x0b } },              // power control
    { 1, { 0xa6 } },                    // normal (non-inverted) display
    { 1, { 0x31 } },                    // exit extension set
    { 4, { 0x32, 0x00, 0x00, 0x05 } },  // scan config
    { 1, { 0x34 } },                    // scroll off
    { 1, { 0x30 } },                    // re-enter extension set
    { 4, { 0xbc, 0x02, 0x01, 0x01 } },  // data scan direction (UI mode)
    { 3, { 0x75, 0x00, 0x3f } },        // rows 0..63
    { 3, { 0x15, 0x00, 0x54 } },        // column addresses 0..84
    { 3, { 0x81, 0x20, 0x02 } },        // electronic volume (final contrast)
    { 1, { 0xaf } },                    // display on
};
const size_t mk1_display_init_cmd_count =
    sizeof(mk1_display_init_cmds) / sizeof(mk1_display_init_cmds[0]);

bool mk1_display_send_cmd(unsigned display, const uint8_t *cmd, size_t len,
                          mk1_ep8_emit_fn emit, void *ctx)
{
    uint8_t packet[3 + MK1_EP8_MAX_PAYLOAD];
    if (display >= MK1_DISPLAY_COUNT || len == 0 || len > MK1_EP8_MAX_PAYLOAD) {
        return false;
    }
    packet[0] = (uint8_t)(display << 1);   // 0x00 = left, 0x02 = right
    packet[1] = (uint8_t)(len >> 8);
    packet[2] = (uint8_t)(len & 0xff);
    memcpy(packet + 3, cmd, len);
    return emit(ctx, packet, len + 3);
}

bool mk1_display_send_frame(unsigned display, const uint8_t fb[MK1_DISPLAY_FB_BYTES],
                            mk1_ep8_emit_fn emit, void *ctx)
{
    static const uint8_t rows[] = { 0x75, 0x00, 0x3f };
    static const uint8_t cols[] = { 0x15, 0x00, 0x54 };
    uint8_t packet[3 + MK1_EP8_MAX_PAYLOAD];
    size_t offset = 0;   // offset into the virtual stream [RAMWR, fb...]
    const size_t total = 1 + MK1_DISPLAY_FB_BYTES;

    if (display >= MK1_DISPLAY_COUNT) return false;
    if (!mk1_display_send_cmd(display, rows, sizeof(rows), emit, ctx)) return false;
    if (!mk1_display_send_cmd(display, cols, sizeof(cols), emit, ctx)) return false;

    while (offset < total) {
        size_t chunk = total - offset;
        if (chunk > MK1_EP8_MAX_PAYLOAD) chunk = MK1_EP8_MAX_PAYLOAD;

        // First chunk uses the panel index, continuations set bit 0.
        packet[0] = (uint8_t)((display << 1) | (offset ? 0x01 : 0x00));
        packet[1] = (uint8_t)(chunk >> 8);
        packet[2] = (uint8_t)(chunk & 0xff);
        if (offset == 0) {
            packet[3] = MK1_ST7529_RAMWR;
            memcpy(packet + 4, fb, chunk - 1);
        } else {
            memcpy(packet + 3, fb + offset - 1, chunk);
        }
        if (!emit(ctx, packet, chunk + 3)) return false;
        offset += chunk;
    }
    return true;
}
